"""Validate the canonical source ledger and regenerate everything derived from it.

  python tools/build_ledger.py           # validate, then write the generated files
  python tools/build_ledger.py --check   # validate and fail if any generated file has drifted

Generated (never edit by hand):
  data/manifests/updated_source_ledger.json  the v2 file in its old shape (README links keep working)
  docs/DATA_SOURCES.md                       the ledger as a table
  docs/submission/NASA_DATA_USED.md          NASA/USGS data actually used, from the ledger
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from science.sources import ledger  # noqa: E402

LEGACY_PATH = ROOT / "data/manifests/updated_source_ledger.json"
DATA_SOURCES = ROOT / "docs/DATA_SOURCES.md"
NASA_DATA_USED = ROOT / "docs/submission/NASA_DATA_USED.md"
TO_LEGACY = {"INGESTED": "USED_AND_INGESTED", "QUERIED LIVE": "USED", "REFERENCE ONLY": "USED_AS_REFERENCE",
             "CATALOGED NOT INGESTED": "CATALOGUED_NOT_INGESTED", "UNAVAILABLE": "UNAVAILABLE"}
TEAM_TYPE = {"COMPUTED": "TEAM_METHOD", "DERIVED": "DERIVED_OUTPUT", "SIMULATED": "TEAM_EXPERIMENT",
             "AI INTERPRETATION": "AI_INTERPRETATION"}
HEADER = "<!-- Generated by tools/build_ledger.py from data/manifests/source_ledger.json. Do not edit. -->\n"


def _base_status(entry: dict) -> str:
    return entry["ingestion_status"].split(" (")[0]


def legacy_json(data: dict) -> str:
    sources, team = [], []
    for e in data["entries"]:
        if "legacy" in e:
            old = e["legacy"]
            item = {"id": old["id"], "organization": e["organization"], "role": old["role"], "status": old["status"]}
            link = e.get("landing_page") or e.get("url")
            if link:
                item["url"] = link
            item["used_for"] = old["used_for"]
            if "note" in old:
                item["note"] = old["note"]
            item.update(old.get("extra", {}))
            sources.append(item)
        elif "legacy_team_output" in e:
            t = e["legacy_team_output"]
            team.append({"id": e["id"], "type": t["type"], "title": e["product_title"], "status": t["status"],
                         **({"url": t["url"]} if "url" in t else {}), "description": t["description"]})
        elif e["organization"] == "NeuroNexus":
            team.append({"id": e["id"], "type": TEAM_TYPE[e["evidence_class"]], "title": e["product_title"],
                         "status": "IMPLEMENTED", "description": "; ".join(e["used_by"]) or e["product_title"]})
        else:
            item = {"id": e["id"], "organization": e["organization"], "role": e["evidence_class"].lower().replace(" ", "_"),
                    "status": TO_LEGACY[_base_status(e)]}
            if e.get("landing_page") or e.get("url"):
                item["url"] = e.get("landing_page") or e.get("url")
            item["used_for"] = e["used_by"] or [e["product_title"]]
            sources.append(item)
    meta = data["legacy_export"]
    out = {"project": meta["project"], "schema_version": meta["schema_version"], "purpose": meta["purpose"],
           "provenance_boundary": meta["provenance_boundary"], "canonical_ledger": "data/manifests/source_ledger.json",
           "sources": sources, "team_outputs": team, "evidence_statuses": meta["evidence_statuses"],
           "project_boundary": meta["project_boundary"]}
    return json.dumps(out, indent=2, ensure_ascii=False) + "\n"


def _link(e: dict) -> str:
    url = e.get("landing_page") or e.get("url")
    return f"[link]({url})" if url else ""


def _cell(text) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def data_sources_md(data: dict) -> str:
    lines = [HEADER, "# Data sources", "",
             f"Canonical ledger: `data/manifests/source_ledger.json` (`{data['schema']}`, {len(data['entries'])} entries). "
             "Every 🏷️ source tag in the console resolves to one of these ids (GET `/sources/{id}`, aliases accepted).", "",
             "Evidence classes: " + "; ".join(f"**{k}**: {v}" for k, v in data["evidence_classes"].items()), ""]
    for cls in data["evidence_classes"]:
        rows = [e for e in data["entries"] if e["evidence_class"] == cls]
        if not rows:
            continue
        lines += [f"## {cls}", "", "| id | organization | product | ingestion | license | verified | link |",
                  "| --- | --- | --- | --- | --- | --- | --- |"]
        for e in sorted(rows, key=lambda r: r["id"]):
            lines.append(f"| `{e['id']}` | {_cell(e['organization'])} | {_cell(e['product_title'])} | "
                         f"{_cell(e['ingestion_status'])} | {_cell(e.get('license'))} | {_cell(e.get('verified_on'))} | {_link(e)} |")
        lines.append("")
    return "\n".join(lines)


def nasa_data_used_md(data: dict) -> str:
    used = [e for e in data["entries"] if e["evidence_class"] in ("OBSERVED", "MODELED", "NASA REFERENCE")
            and _base_status(e) in ("INGESTED", "QUERIED LIVE")]
    lines = [HEADER, "# NASA and partner data used", "",
             "Sources whose data NeuroNexus actually reads (ingested or queried live), from the canonical ledger. "
             "Cataloged-but-not-ingested sources are listed in `docs/DATA_SOURCES.md`.", "",
             "| id | mission / instrument | product | how it is used | status |", "| --- | --- | --- | --- | --- |"]
    for e in sorted(used, key=lambda r: r["id"]):
        mission = " / ".join(x for x in (e.get("mission"), e.get("instrument")) if x) or e["organization"]
        lines.append(f"| `{e['id']}` | {_cell(mission)} | {_cell(e['product_title'])} | "
                     f"{_cell('; '.join(e['used_by']) or e.get('access_method'))} | {_cell(e['ingestion_status'])} |")
    return "\n".join(lines) + "\n"


def outputs(data: dict) -> dict[Path, str]:
    return {LEGACY_PATH: legacy_json(data), DATA_SOURCES: data_sources_md(data), NASA_DATA_USED: nasa_data_used_md(data)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = json.loads(ledger.LEDGER_PATH.read_text(encoding="utf-8"))
    problems = ledger.validate(data)
    if problems:
        print("ledger invalid:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    drift = []
    for path, text in outputs(data).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if drift:
        print("generated files drifted (run python tools/build_ledger.py): " + ", ".join(drift), file=sys.stderr)
        return 1
    print(f"ledger ok: {len(data['entries'])} entries" + ("" if args.check else "; generated files written"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
